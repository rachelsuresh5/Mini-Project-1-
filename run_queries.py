"""Step 3 - Run every query in sql/analysis_queries.sql against db/tmdb.db.

Saves each result to reports/query_results/<name>.csv and writes a combined
Markdown report (reports/sql_results.md) with the question and result table.

Run:  python src/run_queries.py
"""
import re
import sqlite3

import pandas as pd

from config import DB_PATH, QUERY_RESULTS_DIR, REPORTS_DIR, SQL_DIR


def parse_queries(text: str) -> list[dict]:
    """Split the SQL file on '-- name:' markers."""
    blocks = re.split(r"^-- name:\s*", text, flags=re.M)[1:]
    out = []
    for b in blocks:
        name, rest = b.split("\n", 1)
        q = re.search(r"^-- question:\s*(.+)$", rest, flags=re.M)
        sql = "\n".join(l for l in rest.splitlines() if not l.startswith("--")).strip()
        out.append({"name": name.strip(), "question": q.group(1).strip() if q else "", "sql": sql})
    return out


def load_queries() -> list[dict]:
    return parse_queries((SQL_DIR / "analysis_queries.sql").read_text())


def main() -> None:
    QUERY_RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    md = ["# SQL analysis results", "",
          "Generated by `src/run_queries.py` from `sql/analysis_queries.sql`.", ""]
    for q in load_queries():
        df = pd.read_sql_query(q["sql"], con)
        df.to_csv(QUERY_RESULTS_DIR / f"{q['name']}.csv", index=False)
        print(f"{q['name']:<32} {len(df):>3} rows")
        md += [f"## {q['name']}", "", f"**{q['question']}**", "",
               "```sql", q["sql"], "```", "", df.to_markdown(index=False), ""]
    (REPORTS_DIR / "sql_results.md").write_text("\n".join(md))
    con.close()


if __name__ == "__main__":
    main()
