"""Step 2 - Load the cleaned tables into SQLite with SQLAlchemy, then run a test JOIN.

Creates db/tmdb.db from sql/schema.sql, loads data/processed/*.csv with
pandas.DataFrame.to_sql through a SQLAlchemy engine (parents before children so
foreign keys resolve), verifies row counts and foreign-key integrity, and runs a
test JOIN across movies, movie_genres and genres before any analysis.
The test result is saved to reports/db_load_check.md.

Run:  python src/build_db.py
"""
import pandas as pd
from sqlalchemy import create_engine, event, text

from config import DB_PATH, PROCESSED_DIR, REPORTS_DIR, SQL_DIR

# Parents first so foreign keys resolve on insert.
LOAD_ORDER = ["movies", "genres", "keywords", "people", "jobs",
              "movie_genres", "movie_keywords", "cast_credits", "crew_credits"]

TEST_JOIN = """
SELECT m.title, m.release_year, g.genre_name
FROM movies m
JOIN movie_genres mg ON mg.movie_id = m.movie_id
JOIN genres g        ON g.genre_id  = mg.genre_id
WHERE m.title IN ('Interstellar', 'Inception', 'The Dark Knight')
ORDER BY m.title, g.genre_name
"""

TEST_COUNTS = """
SELECT g.genre_name, COUNT(*) AS films
FROM movies m
JOIN movie_genres mg ON mg.movie_id = m.movie_id
JOIN genres g        ON g.genre_id  = mg.genre_id
GROUP BY g.genre_name
ORDER BY films DESC
LIMIT 5
"""


def get_engine():
    engine = create_engine(f"sqlite:///{DB_PATH}")

    @event.listens_for(engine, "connect")
    def _fk_on(dbapi_con, _):  # SQLite only enforces foreign keys when asked
        dbapi_con.execute("PRAGMA foreign_keys = ON")

    return engine


def create_schema(engine) -> None:
    raw = engine.raw_connection()
    try:
        raw.driver_connection.executescript((SQL_DIR / "schema.sql").read_text())
        raw.commit()
    finally:
        raw.close()


def load_tables(engine) -> dict[str, int]:
    counts = {}
    for table in LOAD_ORDER:
        df = pd.read_csv(PROCESSED_DIR / f"{table}.csv")
        if table == "movies":
            df["release_date"] = pd.to_datetime(df["release_date"]).dt.strftime("%Y-%m-%d")
        # to_sql appends into the tables created by schema.sql, so keys and constraints apply.
        df.to_sql(table, engine, if_exists="append", index=False, chunksize=5000)
        with engine.connect() as con:
            n = con.execute(text(f"SELECT COUNT(*) FROM {table}")).scalar_one()
        assert n == len(df), f"{table}: loaded {n}, expected {len(df)}"
        counts[table] = n
        print(f"  {table:<15} {n:>7,} rows")
    return counts


def check_integrity(engine) -> None:
    with engine.connect() as con:
        problems = con.execute(text("PRAGMA foreign_key_check")).fetchall()
    assert not problems, f"Foreign key violations: {problems[:5]}"
    print("Foreign key check passed.")


def test_join(engine) -> tuple[pd.DataFrame, pd.DataFrame]:
    with engine.connect() as con:
        sample = pd.read_sql(text(TEST_JOIN), con)
        top = pd.read_sql(text(TEST_COUNTS), con)
    assert len(sample) > 0, "Test JOIN returned no rows - the database did not load correctly"
    return sample, top


def main() -> None:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        DB_PATH.unlink()
    engine = get_engine()
    create_schema(engine)
    counts = load_tables(engine)
    check_integrity(engine)

    sample, top = test_join(engine)
    print("\nTest JOIN (movies -> movie_genres -> genres):")
    print(sample.to_string(index=False))
    print("\nTop genres by film count (same JOIN, aggregated):")
    print(top.to_string(index=False))

    report = ["# Database load check", "",
              "Generated by `src/build_db.py`. The cleaned tables were loaded into SQLite with",
              "**SQLAlchemy** (`create_engine` + `DataFrame.to_sql`), then checked before analysis.", "",
              "## Row counts", "", pd.Series(counts, name="rows").rename_axis("table").to_frame().to_markdown(), "",
              "## Foreign key check", "", "`PRAGMA foreign_key_check` returned no violations.", "",
              "## Test JOIN: movies → movie_genres → genres", "", "```sql", TEST_JOIN.strip(), "```", "",
              sample.to_markdown(index=False), "",
              "## Same JOIN aggregated: top 5 genres", "", "```sql", TEST_COUNTS.strip(), "```", "",
              top.to_markdown(index=False), ""]
    (REPORTS_DIR / "db_load_check.md").write_text("\n".join(report))
    engine.dispose()
    print(f"\nDatabase written to {DB_PATH}")


if __name__ == "__main__":
    main()
